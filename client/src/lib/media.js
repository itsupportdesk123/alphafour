/**
 * Unsplash image helper. Every photo on the site is an id in the PHOTOS map below
 * (each verified to load). Replace them with your own photography before launch.
 * Anywhere a photo id goes, a path starting with / works too: a file in public/, served as it is.
 */
const BASE = 'https://images.unsplash.com/photo-';
const DEFAULT_WIDTHS = [480, 768, 1080, 1600, 2200];

const isLocal = (id) => id.startsWith('/');

export function unsplash(id, { w = 1600, h, q = 78, crop } = {}) {
  if (isLocal(id)) return id;
  const params = new URLSearchParams({ auto: 'format', fit: 'crop', w: String(w), q: String(q) });
  if (h) params.set('h', String(h));
  if (crop) params.set('crop', crop);
  return `${BASE}${id}?${params.toString()}`;
}

/** Ratio is width / height, e.g. 4 / 5 for portrait cards. */
export function unsplashSrcSet(id, { widths = DEFAULT_WIDTHS, ratio, q = 76, crop } = {}) {
  if (isLocal(id)) return undefined;
  return widths
    .map((w) => `${unsplash(id, { w, h: ratio ? Math.round(w / ratio) : undefined, q, crop })} ${w}w`)
    .join(', ');
}

/** Tiny blurred version used as a placeholder while the real image loads. */
export function unsplashBlur(id, ratio) {
  if (isLocal(id)) return undefined;
  return `${BASE}${id}?auto=format&fit=crop&w=40${ratio ? `&h=${Math.round(40 / ratio)}` : ''}&q=30&blur=60`;
}

