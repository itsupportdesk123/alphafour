export const FLAGSHIP = RESIDENCES.find((r) => r.flagship);

export const getResidence = (slug) => RESIDENCES.find((r) => r.slug === slug);

/** False for a project priced on request. */
export const hasPrice = (residence) => Number.isFinite(residence.price);

/** Indicative cost sheet for a residence (all-inclusive estimate). */
export function buildPriceBreakdown(residence, basePrice = residence.price) {
  const floorRise = Math.round(basePrice * 0.03);
  const parking = residence.type === 'Villa' ? 0 : 1_500_000;
  const club = 1_000_000;
  const subtotal = basePrice + floorRise + parking + club;
  const gst = residence.status === 'ready-to-move' || residence.status === 'sold-out' ? 0 : Math.round(subtotal * 0.05);
  const stampDuty = Math.round(subtotal * 0.06);
  const registration = 30_000;
  return [
    { label: 'Base price', amount: basePrice },
    { label: 'Floor rise & view premium', amount: floorRise },
    parking ? { label: 'Covered parking (×2)', amount: parking } : null,
    { label: 'Club membership', amount: club },
    { label: gst ? 'GST (5%)' : 'GST (not applicable, ready to move)', amount: gst },
    { label: 'Stamp duty (6%, indicative)', amount: stampDuty },
    { label: 'Registration', amount: registration },
  ].filter(Boolean);
}
